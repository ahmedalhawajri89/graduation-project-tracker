    /**
     * مفتاح موضوع الرسالة: العنوان أولاً ثم النصّ — كلمة عابرة في النصّ
     * («لتسليمه») لا تغلب عنواناً صريحاً («كشف الدرجات»).
     */
    public static function of(Contact $message): string
    {
        foreach ([$message->subject, $message->message] as $text) {
            foreach (self::TOPICS as $key => $topic) {
                foreach ($topic['words'] as $word) {
                    if (mb_stripos((string) $text, $word) !== false) {
                        return $key;
                    }
                }
            }
        }

        return 'other';
    }

    /**
     * الموضوع كما يُعرض: اسمه بلغة الواجهة. الردّ الجاهز يبقى عربياً —
     * يُرسَل إلى صاحب الرسالة لا إلى من يقرأ اللوحة.
     */
    public static function meta(string $key): array
    {
        $topic = self::TOPICS[$key] ?? self::OTHER;

        return ['label' => __($topic['label'])] + $topic;
    }

    /** عدد الرسائل لكل موضوع — مرّ واحد على الرسائل، فهي قليلة بطبيعتها */
    public static function counts(iterable $messages): array
    {
        $counts = array_fill_keys([...array_keys(self::TOPICS), 'other'], 0);
        foreach ($messages as $m) {
            $counts[self::of($m)]++;
        }

        return $counts;
    }
